import { expect, test } from "bun:test";
import { normalizeWeekdayLabels } from "./stable-dates.ts";

test("normalizes only the year + weekday labels generated by meowpress", () => {
  const weekdays = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];
  for (const weekday of weekdays) {
    expect(normalizeWeekdayLabels(`<span class="weekday">2026, ${weekday}</span>`))
      .toBe(`<span class="weekday">2026 ${weekday}</span>`);
  }
  const article = '<p>2026, Thu</p><span class="weekday">2026 Thu</span>';
  expect(normalizeWeekdayLabels(article)).toBe(article);
});
